"""area.py - what each feature costs in FPGA resources.

    python scripts/area.py [VARIANT ...]          default: every variant below

Builds top_fpga (scripts/build.tcl, the same constraints and neutral instruction image as
scripts/fpga_build.py) once with every feature and once per removal parameter set to 0
(the hardware is not built; the design then behaves as with that switch off):
    base, HAS_FWD=0, HAS_MD=0, HAS_ICACHE=0, HAS_DCACHE=0, HAS_CORE1=0, HAS_VIO=0
into build/<commit>/area/<variant>/ (a variant already built for this commit is reused; a
build that stops on a locked .Xil folder - a Windows file lock - is retried once), then writes docs/results/area.md: each variant's LUT, FF,
BRAM tiles, DSP and timing from its routed reports, and the feature's cost = base - variant.
These are Vivado's numbers for routed designs.
"""
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import fpga_build  # noqa: E402

VARIANTS = [("base", "", "every feature (the demo build)"),
            ("no_fwd", "HAS_FWD=0", "forwarding muxes"),
            ("no_md", "HAS_MD=0", "MUL / DIV units"),
            ("no_icache", "HAS_ICACHE=0", "I-caches (both cores)"),
            ("no_dcache", "HAS_DCACHE=0", "D-cache"),
            ("no_core1", "HAS_CORE1=0", "second core (with its I-cache)"),
            ("no_vio", "HAS_VIO=0", "VIO hook and JTAG debug hub")]


def build(name, generic, out, tries=2):
    s = os.path.join(out, "summary.txt")
    if os.path.exists(s):                        # built earlier for this commit: reuse
        return dict(ln.strip().split("=", 1) for ln in open(s) if "=" in ln)
    os.makedirs(out, exist_ok=True)
    stage = os.path.join(out, "synth_image")
    os.makedirs(stage, exist_ok=True)
    subprocess.run([sys.executable, os.path.join(HERE, "updatemem.py"), "neutral", os.path.join(stage, "imem.hex")],
                   check=True, capture_output=True)
    shutil.copy(os.path.join(ROOT, fpga_build.IMAGE, "dmem.hex"), stage)
    vivado = shutil.which("vivado") or shutil.which("vivado.bat")
    args = [vivado, "-mode", "batch", "-nojournal", "-nolog", "-notrace", "-source", "scripts/build.tcl", "-tclargs",
            "-f", "sim/fpga.f", "-top", "top_fpga", "-xdc", "rtl/board/nexys_a7.xdc",
            "-hex", os.path.relpath(stage, ROOT).replace("\\", "/"), "-out", os.path.relpath(out, ROOT).replace("\\", "/")]
    if generic:
        args += ["-generic", generic.replace("=", ":")]      # build.tcl turns ":" back into "="
    with open(os.path.join(out, "build.log"), "w", newline="\n") as lg:
        # no shell: cmd.exe would split "HAS_FWD=0" at the "="
        subprocess.run(args, cwd=ROOT, stdout=lg, stderr=subprocess.STDOUT, text=True)
    if not os.path.exists(s):
        log = open(os.path.join(out, "build.log"), errors="replace").read()
        if tries > 1 and "could not be deleted and may be locked" in log:   # Windows file lock on .Xil: retry once
            return build(name, generic, out, tries - 1)
        sys.exit("FAIL area: %s did not build (%s)" % (name, os.path.join(out, "build.log")))
    return dict(ln.strip().split("=", 1) for ln in open(s) if "=" in ln)


def main():
    want = sys.argv[1:] or [v[0] for v in VARIANTS]
    base_dir = os.path.join(fpga_build.commit_dir(), "area")
    res = {}
    for name, generic, what in VARIANTS:
        if name in want:
            res[name] = build(name, generic, os.path.join(base_dir, name))
            print("%-10s %-14s LUT %s FF %s BRAM %s DSP %s WNS %s" % (name, generic or "-", res[name]["LUT"], res[name]["FF"],
                  res[name]["BRAM"], res[name]["DSP"], res[name]["WNS"]), flush=True)
    if "base" not in res:
        return
    b = res["base"]
    md = ["# Resources per feature", "",
          "Generated by `python scripts/area.py`: top_fpga built once with every feature and once per removal parameter",
          "set to 0 (Vivado 2025.2, xc7a100tcsg324-1, 50 MHz, routed). Cost = base - variant: the resources the",
          "feature's hardware takes. With a removal parameter at 0 the design behaves as with that switch off.", "",
          "| Variant | Parameter | Removes | LUT | FF | BRAM tiles | DSP | WNS (ns) | Cost: LUT | FF | BRAM | DSP |",
          "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for name, generic, what in VARIANTS:
        if name not in res:
            continue
        r = res[name]
        cost = ["-"] * 4 if name == "base" else [
            "%g" % (float(b[k]) - float(r[k])) for k in ("LUT", "FF", "BRAM", "DSP")]
        md.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            name, generic or "-", what, "{:,}".format(int(float(r["LUT"]))), "{:,}".format(int(float(r["FF"]))),
            r["BRAM"], r["DSP"], r["WNS"], " | ".join(cost)))
    md += ["", "Device: 63,400 LUT, 126,800 FF, 135 BRAM tiles, 240 DSP. Every variant: timing %s." %
           ("met" if all(v["timing"] == "met" for v in res.values()) else "NOT met in some (see WNS)")]
    open(os.path.join(ROOT, "docs", "results", "area.md"), "w", newline="\n").write("\n".join(md) + "\n")
    print("PASS area: docs/results/area.md (%d variants)" % len(res))


if __name__ == "__main__":
    main()
