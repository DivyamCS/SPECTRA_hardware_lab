"""ablation.py - what each feature is worth, from the board's ablation runs.

    python scripts/ablation.py [CSV]          default docs/results/ablation_board.csv

Reads the CSV written by scripts/board_regress.py for scripts/ablation_list.txt (board
measurements: cycles and the STATS counters of both cores) and writes
  docs/results/ablation.md          one table per program: every setting's run time, the factor
                                    against "all on", CPI, D- and I-cache hit rates, arbiter wait;
  docs/results/ablation_<prog>.svg  bar chart of the factor (how many times slower than all on).
Every number is computed from one CSV row, named in the table's first column. Factor =
cycles(setting) / cycles(all on): the speed the feature (or setting) is worth. CPI = cycles /
instructions of core 0 (with two cores both cores run the whole time). Rates in %.
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CLK = 50e6
WHAT = {"all_on": "all on (2 cores, FWD, IC, DC, L = 8)", "fwd_off": "forwarding off",
        "ic_off": "I-caches off", "dc_off": "D-cache off", "dual_off": "one core",
        "L5": "memory latency L = 5", "L10": "memory latency L = 10",
        "all_off": "all off (1 core, no forwarding, no caches, L = 8)"}
NAMES = {"gol": "Game of Life", "matmul": "MatMul 32x32"}


def pct(a, b):
    return 100.0 * a / b if b else 0.0


def svg(prog, rows, path):
    w, bar, gap, left = 760, 22, 8, 270
    h = 40 + len(rows) * (bar + gap)
    top = max(r["factor"] for r in rows)
    scale = (w - left - 80) / top
    out = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" font-family="Segoe UI, sans-serif" font-size="13">' % (w, h),
           '<rect width="100%" height="100%" fill="#ffffff"/>',
           '<text x="10" y="22" font-weight="700">%s on the board: times slower than all on (cycles / cycles of all on)</text>' % NAMES[prog]]
    for i, r in enumerate(rows):
        y = 36 + i * (bar + gap)
        col = "#2a9d8f" if r["factor"] <= 1.0 else "#e76f51"
        out.append('<text x="%d" y="%d" text-anchor="end">%s</text>' % (left - 8, y + bar - 6, WHAT[r["key"]].split(" (")[0]))
        out.append('<rect x="%d" y="%d" width="%.1f" height="%d" fill="%s"/>' % (left, y, max(1.0, r["factor"] * scale), bar, col))
        out.append('<text x="%.1f" y="%d">%.2fx</text>' % (left + r["factor"] * scale + 6, y + bar - 6, r["factor"]))
    out.append('<line x1="%.1f" y1="30" x2="%.1f" y2="%d" stroke="#555" stroke-dasharray="4 3"/>' % (left + scale, left + scale, h - 4))
    out.append("</svg>")
    open(path, "w", newline="\n").write("\n".join(out) + "\n")


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "docs", "results", "ablation_board.csv")
    rows = list(csv.DictReader(open(path)))
    bad = [r["name"] for r in rows if r["result"] != "ok" or r["checksum_ok"] != "1"]
    if bad:
        sys.exit("FAIL ablation: runs not golden: %s" % ", ".join(bad))
    md = ["# Ablation on the board", "",
          "Generated by `python scripts/ablation.py` from %s (scripts/board_regress.py with "
          "scripts/ablation_list.txt; board measurements, every run golden and equal to rv32sim's packets). "
          "Factor = cycles / cycles of \"all on\" (above 1: slower without the feature). CPI = cycles / "
          "instructions of core 0; rates in %% of core 0's accesses (core 1 where shown)." % os.path.relpath(path, ROOT).replace("\\", "/"), ""]
    for prog in ("gol", "matmul"):
        pr = [r for r in rows if r["name"].startswith(prog + "_")]
        base = next(int(r["board_cycles"]) for r in pr if r["name"] == prog + "_all_on")
        table = []
        for r in pr:
            key = r["name"][len(prog) + 1:]
            cyc = int(r["board_cycles"])
            c = {k: int(r[k]) if r[k] else 0 for k in r if k[:3] in ("c0_", "c1_")}
            table.append({"key": key, "row": r["name"], "cfg": r["config"], "cyc": cyc, "factor": cyc / base,
                          "cpi": cyc / c["c0_instret"], "dhit": pct(c["c0_dhit"], c["c0_dhit"] + c["c0_dmiss"]),
                          "ihit": pct(c["c0_ihit"], c["c0_ihit"] + c["c0_imiss"]),
                          "dhit1": pct(c["c1_dhit"], c["c1_dhit"] + c["c1_dmiss"]) if r["cores"] == "2" else None,
                          "arb": pct(c["c0_arbwait"], cyc), "cores": r["cores"],
                          "dc": int(r["config"], 16) >> 1 & 1, "ic": int(r["config"], 16) >> 7 & 1})
        md += ["## %s" % NAMES[prog], "",
               "| CSV row | Setting | CONFIG | Cores | Cycles | Time | Factor | CPI c0 | D-hit c0 | D-hit c1 | I-hit c0 | Arbiter wait c0 |",
               "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
        for t in table:
            md.append("| %s | %s | 0x%s | %s | %s | %s | %.2fx | %.2f | %s | %s | %s | %.2f %% |" % (
                t["row"], WHAT[t["key"]], t["cfg"].upper(), t["cores"], "{:,}".format(t["cyc"]),
                ("%.3f s" % (t["cyc"] / CLK)) if t["cyc"] >= CLK else ("%.2f ms" % (t["cyc"] / CLK * 1e3)),
                t["factor"], t["cpi"], ("%.2f %%" % t["dhit"]) if t["dc"] else "-",
                ("%.2f %%" % t["dhit1"]) if t["dhit1"] is not None and t["dc"] else "-",
                ("%.2f %%" % t["ihit"]) if t["ic"] else "-", t["arb"]))
        rank = sorted((t for t in table if t["key"] not in ("all_on", "all_off")), key=lambda t: -t["factor"])
        md += ["", "Worth the most (largest factor without it): " +
               ", ".join("%s %.2fx" % (WHAT[t["key"]].split(" (")[0], t["factor"]) for t in rank[:4]) + ". "
               "All off is %.1fx slower than all on." % next(t["factor"] for t in table if t["key"] == "all_off"), "",
               "![%s](ablation_%s.svg)" % (NAMES[prog], prog), ""]
        svg(prog, table, os.path.join(ROOT, "docs", "results", "ablation_%s.svg" % prog))
    open(os.path.join(ROOT, "docs", "results", "ablation.md"), "w", newline="\n").write("\n".join(md))
    print("PASS ablation: docs/results/ablation.md, ablation_gol.svg, ablation_matmul.svg from %d CSV rows" % len(rows))


if __name__ == "__main__":
    main()
