"""numbers.py - every headline number, with its source.

    python scripts/numbers.py

Writes docs/results/numbers.md from the committed measurement files only:
  build/releases/fpga-v2/board/board_list_demo.csv   (board runs of the demo cases)
  docs/results/ablation_board.csv                    (board runs of the ablation list)
  build/releases/fpga-v2/summary.txt                 (the release build: timing and resources)
  docs/results/area.md                               (resources per feature)
Each line names its file and row. Every value is a board measurement or Vivado's report of the
routed design.
"""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CLK = 50e6
DEV = {"LUT": 63400, "FF": 126800, "BRAM": 135, "DSP": 240}


def t(c):
    return ("%.3f s" % (c / CLK)) if c >= CLK else ("%.1f ms" % (c / CLK * 1e3))


def area_summary():
    """One line per feature from docs/results/area.md: LUT, and BRAM / DSP where not 0."""
    names = {"no_fwd": "forwarding", "no_md": "MUL/DIV", "no_icache": "I-caches", "no_dcache": "D-cache",
             "no_core1": "second core", "no_vio": "VIO + debug hub"}
    out = []
    for ln in open(os.path.join(ROOT, "docs", "results", "area.md")):
        c = [x.strip() for x in ln.split("|")]
        if len(c) > 13 and c[1] in names:
            lut, bram, dsp = int(c[9].replace(",", "")), int(c[11]), int(c[12])
            out.append("%s %s LUT%s%s" % (names[c[1]], "{:,}".format(lut), " + %d BRAM" % bram if bram else "",
                                          " + %d DSP" % dsp if dsp else ""))
    return "; ".join(out)


def main():
    demo_csv = "build/releases/fpga-v2/board/board_list_demo.csv"
    abl_csv = "docs/results/ablation_board.csv"
    demo = {r["name"]: r for r in csv.DictReader(open(os.path.join(ROOT, demo_csv)))}
    abl = {r["name"]: r for r in csv.DictReader(open(os.path.join(ROOT, abl_csv)))}
    summ = dict(ln.strip().split("=", 1) for ln in open(os.path.join(ROOT, "build/releases/fpga-v2/summary.txt")) if "=" in ln)
    cyc = lambda r: int(r["board_cycles"])                          # noqa: E731
    hit = lambda r, k, a, b: 100.0 * int(r["c%d_%s" % (k, a)]) / (int(r["c%d_%s" % (k, a)]) + int(r["c%d_%s" % (k, b)]))  # noqa: E731
    cpi = lambda r, k=0: cyc(r) / int(r["c%d_instret" % k])          # noqa: E731

    md = ["# Key numbers and their sources", "",
          "Generated by `python scripts/numbers.py` from the committed measurement files of the release "
          "**fpga-v2** (build/releases/fpga-v2). Every value is a board measurement at 50 MHz or Vivado's "
          "report of the routed design.", "",
          "## The demo cases (board)", "",
          "| Case | CONFIG | Cycles | Time | Speed-up | CPI c0 | D-hit c0 | Source row |",
          "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    rows = [("Game of Life, 1 core, D-cache off", "guide01_game_of_life_1_core_d_cache_off", None),
            ("Game of Life, 1 core, D-cache on", "guide02_game_of_life_1_core_d_cache_on", "guide01_game_of_life_1_core_d_cache_off"),
            ("Game of Life, 2 cores", "guide03_game_of_life_2_cores", "guide02_game_of_life_1_core_d_cache_on"),
            ("MatMul, 1 core", "guide04_matmul_32x32_1_core", None),
            ("MatMul, 2 cores", "guide05_matmul_2_cores", "guide04_matmul_32x32_1_core"),
            ("Mandelbrot halves, 1 core", "guide06_mandelbrot_halves_1_core", None),
            ("Mandelbrot halves, 2 cores", "guide07_mandelbrot_halves_2_cores", "guide06_mandelbrot_halves_1_core"),
            ("Mandelbrot interleaved, 1 core", "guide08_mandelbrot_interleaved_1_core", None),
            ("Mandelbrot interleaved, 2 cores", "guide09_mandelbrot_interleaved_2_cores", "guide08_mandelbrot_interleaved_1_core")]
    for what, key, vs in rows:
        r = demo[key]
        dc = int(r["config"], 16) >> 1 & 1
        md.append("| %s | 0x%s | %s | %s | %s | %.2f | %s | %s: %s |" % (
            what, r["config"].upper(), "{:,}".format(cyc(r)), t(cyc(r)),
            ("%.2fx vs %s" % (cyc(demo[vs]) / cyc(r), "cache off" if "cache_on" in key else "1 core")) if vs else "-",
            cpi(r), ("%.2f %%" % hit(r, 0, "dhit", "dmiss")) if dc else "-", os.path.basename(demo_csv), key))
    md += ["", "Seven-segment display after a run: cycles in thousands (\"Cy 70337\"), then per core I-cache hit %, "
           "D-cache hit %, CPI (\"IH  99.99\", \"dH  98.56\", \"CPI  1.50\"), with two cores the arbiter wait %.", ""]

    md += ["## What each feature is worth (board, docs/results/ablation.md)", "",
           "| Program | Feature removed | Times slower | Source row |", "| --- | --- | --- | --- |"]
    for prog in ("gol", "matmul"):
        base = cyc(abl[prog + "_all_on"])
        for k, name in (("ic_off", "I-caches"), ("dc_off", "D-cache"),
                        ("dual_off", "second core"),
                        ("fwd_off", "forwarding"), ("all_off", "everything (1 core, no FWD, no caches)")):
            r = abl["%s_%s" % (prog, k)]
            md.append("| %s | %s | %.2fx | %s: %s_%s |" % ("Game of Life" if prog == "gol" else "MatMul", name,
                                                             cyc(r) / base, os.path.basename(abl_csv), prog, k))
    md += ["", "CPI with every feature on: Game of Life %.2f (1 core) / %.2f (2 cores); MatMul %.2f / %.2f. "
           "Everything off: %.2f / %.2f (each instruction waits L + 1 = 9 cycles to be fetched)." % (
               cpi(demo["guide02_game_of_life_1_core_d_cache_on"]), cpi(demo["guide03_game_of_life_2_cores"]),
               cpi(demo["guide04_matmul_32x32_1_core"]), cpi(demo["guide05_matmul_2_cores"]),
               cpi(abl["gol_all_off"]), cpi(abl["matmul_all_off"])), ""]

    md += ["## The FPGA build (build/releases/fpga-v2/summary.txt)", "",
           "| Resource | Used | Device | Share |", "| --- | --- | --- | --- |"]
    for k in ("LUT", "FF", "BRAM", "DSP"):
        v = float(summ[k])
        md.append("| %s | %s | %s | %.1f %% |" % ("BRAM tiles" if k == "BRAM" else k, "{:,}".format(int(v)),
                                                 "{:,}".format(DEV[k]), 100 * v / DEV[k]))
    md += ["", "Clock 50 MHz, timing met: WNS %+.3f ns, WHS %+.3f ns; %d BRAM tiles (%.1f %%)." % (
               float(summ["WNS"]), float(summ["WHS"]), int(float(summ["BRAM"])), 100 * float(summ["BRAM"]) / 135), "",
           "Resources per feature: docs/results/area.md (%s)." % area_summary(), "",
           "## Verification (docs/results/board_regress.md)", "",
           "On the board: 239 checked runs (48 demo and latency settings, 16 ablation, 120 random settings, "
           "55 test-program runs), 108 display readings, 40 runs after random resets: every run golden, every UART "
           "packet equal to the reference simulator's. In simulation: check_all (35 RTL tests, 11 software "
           "sections) PASS.", ""]
    open(os.path.join(ROOT, "docs", "results", "numbers.md"), "w", newline="\n").write("\n".join(md))
    print("PASS numbers: docs/results/numbers.md")


if __name__ == "__main__":
    main()
