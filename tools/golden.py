"""golden.py - Python models of every SPECTRA program, bit-exact with the firmware.

  python tools/golden.py                 print the golden checksums
  python tools/golden.py --header PATH   write fw/golden.h

The dashboard imports this module to check each run's checksum and to draw reference images.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mext_ref  # noqa: E402

M32 = 0xFFFFFFFF


def fnv1a(data):
    h = 0x811C9DC5
    for b in data:
        h ^= b
        h = (h * 0x01000193) & M32
    return h


def lcg(s):
    return (s * 1664525 + 1013904223) & M32


# ---------------- Game of Life (fw/gol.c) ----------------
GOL_W, GOL_H, GOL_GENS = 64, 64, 400


def gol_initial():
    s, g = 0xC0FFEE11, bytearray(GOL_W * GOL_H)
    for i in range(GOL_W * GOL_H):
        r, c = divmod(i, GOL_W)
        s = lcg(s)
        g[i] = 1 if ((s >> 28) < 4 and 0 < r < GOL_H - 1 and 0 < c < GOL_W - 1) else 0
    return g


def gol_step(src):
    W, H = GOL_W, GOL_H
    dst = bytearray(W * H)
    for r in range(1, H - 1):
        up, mid, dn = (r - 1) * W, r * W, (r + 1) * W
        for c in range(1, W - 1):
            n = (src[up + c - 1] + src[up + c] + src[up + c + 1] + src[mid + c - 1] + src[mid + c + 1]
                 + src[dn + c - 1] + src[dn + c] + src[dn + c + 1])
            dst[mid + c] = 1 if (n == 3 or (n == 2 and src[mid + c])) else 0
    return dst


def gol_frames():
    """List of all 401 grids (generation 0 .. 400)."""
    g = gol_initial()
    out = [bytes(g)]
    for _ in range(GOL_GENS):
        g = gol_step(g)
        out.append(bytes(g))
    return out


def gol_checksum(frames=None):
    frames = frames or gol_frames()
    return fnv1a(frames[GOL_GENS])


# ---------------- Mandelbrot (fw/mandel.c) ----------------
MB_W, MB_H, MB_MAXIT, MB_FRAC, MB_X0, MB_Y0, MB_STEP = 192, 144, 64, 12, -8192, -4392, 61


def _s32(x):
    x &= M32
    return x - (1 << 32) if x & 0x80000000 else x


def mb_pixel(cr, ci):
    zr = zi = 0
    n = 0
    while n < MB_MAXIT:
        zr2 = _s32(zr * zr) >> MB_FRAC
        zi2 = _s32(zi * zi) >> MB_FRAC
        if zr2 + zi2 > (4 << MB_FRAC):
            break
        zi = _s32((_s32(zr * zi) >> (MB_FRAC - 1)) + ci)
        zr = _s32(zr2 - zi2 + cr)
        n += 1
    return n


def mb_image():
    img = bytearray(MB_W * MB_H)
    for r in range(MB_H):
        ci = MB_Y0 + r * MB_STEP
        for c in range(MB_W):
            img[r * MB_W + c] = mb_pixel(MB_X0 + c * MB_STEP, ci)
    return bytes(img)


def mb_checksum(img=None):
    return fnv1a(img or mb_image())


# ---------------- MatMul (fw/matmul.c) ----------------
MM_N = 32


def mm_inputs():
    s = 0x5EED1234
    mats = []
    for _ in range(2):
        m = []
        for _ in range(MM_N * MM_N):
            s = lcg(s)
            m.append((s >> 24) & 15)
        mats.append(m)
    return mats


def mm_result():
    a, b = mm_inputs()
    n = MM_N
    c = [0] * (n * n)
    for i in range(n):
        for k in range(n):
            av = a[i * n + k]
            for j in range(n):
                c[i * n + j] = (c[i * n + j] + av * b[k * n + j]) & M32
    return c


def mm_checksum(c=None):
    c = c or mm_result()
    return fnv1a(b"".join(v.to_bytes(4, "little") for v in c))


def mm_heat(v):
    """What the streamer sends per element of C in an MROW packet."""
    return min(255, v >> 5)


# ---------------- t_mext (fw/tests/t_mext.c) ----------------
MEXT_EDGE = [0x00000000, 0x00000001, 0xFFFFFFFF, 0x00000002, 0xFFFFFFFE, 0x80000000, 0x7FFFFFFF,
             0x00007FFF, 0x00008000, 0x0000FFFF, 0x00010000, 0x00003039, 0xFFFE7E33]


def mext_checksum():
    h = 0x811C9DC5

    def ops(a, b):
        nonlocal h
        for name in mext_ref.ORDER:
            h = ((h ^ mext_ref.OPS[name](a, b)) * 0x01000193) & M32

    for a in MEXT_EDGE:
        for b in MEXT_EDGE:
            ops(a, b)
    s = 0x13579BDF
    for _ in range(1000):
        s = lcg(s)
        a = s
        s = lcg(s)
        b = s >> (s & 31)
        ops(a, b)
    return h


def all_golden():
    return {"GOLD_GOL": gol_checksum(), "GOLD_MANDEL": mb_checksum(),
            "GOLD_MATMUL": mm_checksum(), "GOLD_MEXT": mext_checksum()}


def write_header(path, g):
    lines = ["/* golden.h - generated by tools/golden.py; do not edit. */",
             "#ifndef GOLDEN_H", "#define GOLDEN_H"]
    lines += ["#define %-12s 0x%08Xu" % (k, v) for k, v in g.items()]
    lines += ["#endif", ""]
    text = "\n".join(lines)
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w", newline="\n") as f:
            f.write(text)


if __name__ == "__main__":
    g = all_golden()
    for k, v in g.items():
        print("%-12s 0x%08X" % (k, v))
    if "--header" in sys.argv:
        write_header(sys.argv[sys.argv.index("--header") + 1], g)
