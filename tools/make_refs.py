"""make_refs.py - reference commit traces and UART streams from rv32sim.

    python tools/make_refs.py            generate everything into tb/ref/ and check it
    python tools/make_refs.py --verify   re-check existing files against tb/ref/MANIFEST.json

Commit traces (`rv32sim -t`), one core, FWD = 1 and FWD = 0:
    t_hazard, t_mext, and the demo image with each program (SW6:5): gol, mandel_halves,
    mandel_interleaved, matmul -> tb/ref/trace_<name>_fwd1.txt and _fwd0.txt.
    Traces are large (Game of Life: tens of millions of lines), so they are NOT committed: they
    are regenerated by this script (rv32sim is deterministic) and checked against the SHA-256
    and line count in MANIFEST.json, which is committed.
    FWD changes only timing, so tools/tracecmp.py must find the FWD = 0 and FWD = 1 traces equal
    once the value read from CONFIG (0x92 vs 0x93) is masked (it stops at the first CYCLES read;
    values after it depend on timing, PROTOCOL.md v1.1).
UART streams (`rv32sim -u`): every demo program on 1 and 2 cores ->
    tb/ref/uart_<program>_<n>c.bin (committed). Every packet must decode with host/protocol.py,
    BEGIN first, STATS last, no byte dropped or left over, and the STATS
    checksum must be golden.
"""
import hashlib
import json
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(ROOT, "host"))
import golden  # noqa: E402
import protocol  # noqa: E402
from simpath import find_sim  # noqa: E402

REF = os.path.join(ROOT, "tb", "ref")
BASE = 0x0093                      # FWD DC IC, L = 8, PLRU, write-back, 4 ways, 1 core
PROGRAMS = {"gol": 0, "mandel_halves": 1, "mandel_interleaved": 2, "matmul": 3}
TRACES = [("t_hazard", "t_hazard", 0), ("t_mext", "t_mext", 0)] + \
         [(p, "demo", n) for p, n in PROGRAMS.items()]
GOLD = {"gol": golden.gol_checksum, "mandel_halves": golden.mb_checksum,
        "mandel_interleaved": golden.mb_checksum, "matmul": golden.mm_checksum}


def sha_lines(path):
    h, n = hashlib.sha256(), 0
    with open(path, "rb") as f:
        for line in f:
            h.update(line)
            n += 1
    return h.hexdigest(), n


def trace(sim, image, cfg, prefix):
    subprocess.run([sim, "-c", "%04x" % cfg, "-t", prefix, os.path.join(ROOT, "fw", "build", image)],
                   capture_output=True)
    return prefix + "0.txt"


def main():
    os.makedirs(REF, exist_ok=True)
    sim = find_sim()
    manifest = {"rv32sim": "sim/rv32sim.c", "config_fwd1": "%04x" % BASE, "traces": {}, "uart": {}}
    tmp = tempfile.mkdtemp()
    for name, image, prog in TRACES:
        cfg = BASE | (prog << 5)
        entry = {"image": image}
        files = {}
        for fwd in (1, 0):
            c = cfg if fwd else cfg & ~1
            t = trace(sim, image, c, os.path.join(tmp, "%s_f%d_" % (name, fwd)))
            dst = os.path.join(REF, "trace_%s_fwd%d.txt" % (name, fwd))
            os.replace(t, dst)
            r = subprocess.run([sys.executable, os.path.join(ROOT, "tools", "tracecmp.py"), dst, dst],
                               capture_output=True, text=True)
            assert r.returncode == 0, name + ": tracecmp of the trace with itself failed"
            h, n = sha_lines(dst)
            entry["fwd%d" % fwd] = {"config": "%04x" % c, "lines": n, "sha256": h, "tracecmp_self": r.stdout.strip()}
            files[fwd] = dst
        # FWD changes only timing: the traces must agree except the value read from CONFIG
        masked = []
        for fwd in (1, 0):
            mp = os.path.join(tmp, "%s_masked%d.txt" % (name, fwd))
            with open(files[fwd]) as fi, open(mp, "w", newline="\n") as fo:
                for line in fi:
                    if line.rstrip().endswith("ld 20000008"):
                        p = line.split()
                        line = " ".join(p[:2] + [p[2].split("=")[0] + "=CONFIG"] + p[3:]) + "\n"
                    fo.write(line)
            masked.append(mp)
        r0 = subprocess.run([sys.executable, os.path.join(ROOT, "tools", "tracecmp.py")] + masked,
                            capture_output=True, text=True)
        assert r0.returncode == 0, name + ": FWD = 0 trace differs from FWD = 1: " + r0.stdout
        entry["fwd0_vs_fwd1"] = r0.stdout.strip() + " (CONFIG value masked)"
        manifest["traces"][name] = entry
        print("trace %-20s %10d lines  FWD=0 vs 1: %s" % (name, entry["fwd1"]["lines"], r0.stdout.strip()),
              flush=True)
    for prog, n in PROGRAMS.items():
        for cores in (1, 2):
            cfg = BASE | (n << 5) | (4 if cores == 2 else 0)
            dst = os.path.join(REF, "uart_%s_%dc.bin" % (prog, cores))
            subprocess.run([sim, "-c", "%04x" % cfg, "-u", dst, os.path.join(ROOT, "fw", "build", "demo")],
                           capture_output=True)
            data = open(dst, "rb").read()
            parser = protocol.Parser()
            pk = list(parser.feed(data))
            types = [p["type"] for p in pk]
            assert parser.dropped == 0 and not parser.buf, (prog, cores, "undecodable bytes")
            assert types and types[0] == "BEGIN" and types[-1] == "STATS", (prog, cores, types[:3])
            assert pk[-1]["checksum"] == GOLD[prog](), (prog, cores)
            counts = {t: types.count(t) for t in sorted(set(types))}
            manifest["uart"]["%s_%dc" % (prog, cores)] = {"config": "%04x" % cfg, "bytes": len(data),
                                                         "sha256": hashlib.sha256(data).hexdigest(),
                                                         "packets": counts}
            print("uart  %-22s %7d bytes  %s  STATS checksum golden" % ("%s_%dc" % (prog, cores), len(data), counts),
                  flush=True)
    with open(os.path.join(REF, "MANIFEST.json"), "w", newline="\n") as f:
        json.dump(manifest, f, indent=1)
    print("make_refs: PASS")


def verify():
    m = json.load(open(os.path.join(REF, "MANIFEST.json")))
    for name, e in m["traces"].items():
        for fwd in (1, 0):
            f = os.path.join(REF, "trace_%s_fwd%d.txt" % (name, fwd))
            assert sha_lines(f) == (e["fwd%d" % fwd]["sha256"], e["fwd%d" % fwd]["lines"]), f
    for name, e in m["uart"].items():
        data = open(os.path.join(REF, "uart_%s.bin" % name), "rb").read()
        assert hashlib.sha256(data).hexdigest() == e["sha256"], name
    print("make_refs --verify: PASS")


if __name__ == "__main__":
    verify() if "--verify" in sys.argv else main()
